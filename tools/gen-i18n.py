#!/usr/bin/env python3
"""Builds wwwroot/app/js/i18n/th.js and en.js from tools/i18n/*.tsv (key<TAB>thai<TAB>english).
Keeping both languages on one line makes a missing translation impossible to miss.
    python3 -I tools/gen-i18n.py
"""
import json, pathlib, sys

here = pathlib.Path(__file__).resolve().parent
out = here.parent / "src" / "Mecmat.Server" / "wwwroot" / "app" / "js" / "i18n"
th, en, seen, bad = {}, {}, {}, []
for f in sorted((here / "i18n").glob("*.tsv")):
    for n, line in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) != 3 or not all(p.strip() for p in parts):
            bad.append(f"{f.name}:{n}: {line[:60]}")
            continue
        k, t, e = parts
        if k in seen:
            bad.append(f"{f.name}:{n}: duplicate {k} (first in {seen[k]})")
        seen[k] = f.name
        th[k], en[k] = t, e
if bad:
    print("\n".join(bad)); sys.exit(1)
for name, d in (("th", th), ("en", en)):
    (out / f"{name}.js").write_text("// Generated by tools/gen-i18n.py — edit tools/i18n/*.tsv instead.\nexport default "
                                    + json.dumps(d, ensure_ascii=False, indent=0, sort_keys=True) + ";\n", encoding="utf-8")
print(f"{len(th)} keys")
