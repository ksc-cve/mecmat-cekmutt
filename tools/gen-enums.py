#!/usr/bin/env python3
"""Writes wwwroot/app/js/enums.js from the C# enums in Domain/, so the UI's option lists can
never drift from what the server accepts. Run after changing any enum:
    python3 -I tools/gen-enums.py
"""
import json, pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent / "src" / "Mecmat.Server"
enums = {}
for f in sorted((root / "Domain").glob("*.cs")):
    src = re.sub(r"//.*", "", f.read_text(encoding="utf-8"))
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    for name, body in re.findall(r"public enum (\w+)\s*\{([^}]*)\}", src):
        enums[name] = [re.sub(r"\s*=.*", "", v).strip() for v in body.split(",") if v.strip()]
out = root / "wwwroot" / "app" / "js" / "enums.js"
out.write_text("// Generated by tools/gen-enums.py from Domain/*.cs — do not edit by hand.\nexport const ENUMS = "
               + json.dumps(enums, indent=1, ensure_ascii=False) + ";\n", encoding="utf-8")
print(f"{len(enums)} enums → {out.relative_to(root)}")
