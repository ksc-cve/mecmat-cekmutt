import { dashboardPage } from './dashboard.js';
import { peoplePage, personPage, profilePage, organizationsPage } from './people.js';
import { publicationsPage, publicationPage } from './publications.js';
import { projectsPage, projectPage } from './projects.js';
import { financePage, accountPage, requestPage } from './finance.js';
import { approvalsPage } from './approvals.js';
import { bookingsPage, calendarPage } from './bookings.js';
import { tasksPage, taskPage, meetingsPage, meetingPage } from './work.js';
import { assetsPage, assetPage, documentsPage, documentPage } from './assets.js';
import { newsPage, recruitmentsPage, inboxPage, sitePage } from './website.js';
import { usersPage, rolesPage, authorityPage, resourcesAdminPage, auditPage } from './admin.js';
import { totpSetupScreen } from '../auth.js';
import { page } from '../shell.js';

export function registerPages(route) {
  route('/', dashboardPage);
  route('/people', peoplePage);
  route('/people/:id', personPage);
  route('/profile', profilePage);
  route('/profile/totp', () => totpSetupScreen(page('profile.totpSetup'), { onDone: () => location.replace('#/profile') }));
  route('/organizations', organizationsPage);
  route('/publications', publicationsPage);
  route('/publications/:id', publicationPage);
  route('/projects', projectsPage);
  route('/projects/:id', projectPage);
  route('/finance', financePage);
  route('/finance/accounts/:id', accountPage);
  route('/finance/requests/:id', requestPage);
  route('/approvals', approvalsPage);
  route('/bookings', bookingsPage);
  route('/calendar', calendarPage);
  route('/tasks', tasksPage);
  route('/tasks/:id', taskPage);
  route('/meetings', meetingsPage);
  route('/meetings/:id', meetingPage);
  route('/assets', assetsPage);
  route('/assets/:id', assetPage);
  route('/documents', documentsPage);
  route('/documents/:id', documentPage);
  route('/news', newsPage);
  route('/recruitments', recruitmentsPage);
  route('/inbox', inboxPage);
  route('/site', sitePage);
  route('/admin/users', usersPage);
  route('/admin/roles', rolesPage);
  route('/admin/authority', authorityPage);
  route('/admin/resources', resourcesAdminPage);
  route('/admin/audit', auditPage);
}
